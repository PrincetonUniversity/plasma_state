    ierr = 0
    if (ndims /= 1) ierr = 1
    call ccps_argcheck('psgetdim_chiphi_neo', iobj, ierr)
    if(ierr.ne.0) return
    ! proceed...
    call load_ps_container(iobj,ptr)
    ss => ptr % ps_ptr
    dims = 0
    if (allocated( ss % chiphi_neo ) ) then
        ! can only call 'shape' on allocated/associated arrays
        dims = shape(ss % chiphi_neo)
    endif
end subroutine psgetdim_chiphi_neo

