    ! local
    type (plasma_state_container) :: ptr
    type (plasma_state), pointer  :: ss

    ierr = 0
    if (ndims /= 1) ierr = 1
    call ccps_argcheck('psgetdim_chii_gtcneo', iobj, ierr)
    if(ierr.ne.0) return
    ! proceed...
    call load_ps_container(iobj,ptr)
    ss => ptr % ps_ptr
    dims = 0
    if (allocated( ss % chii_gtcneo ) ) then
        ! can only call 'shape' on allocated/associated arrays
        dims = shape(ss % chii_gtcneo)
    endif
end subroutine psgetdim_chii_gtcneo

